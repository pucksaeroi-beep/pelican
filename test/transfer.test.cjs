'use strict';
const test = require('node:test');
const assert = require('node:assert');
const { category, targetType, createTableSql, convert, nameFor } = require('../electron/transfer.cjs');

test('column types are read into categories', () => {
  const c = (type, d = 'pg') => category({ type }, d).cat;
  assert.strictEqual(c('integer'), 'int');
  assert.strictEqual(c('character varying(60)'), 'varchar');
  assert.strictEqual(c('timestamp with time zone'), 'tstz');
  assert.strictEqual(c('timestamp without time zone'), 'ts');
  assert.strictEqual(c('jsonb'), 'json');
  assert.strictEqual(c('bytea'), 'bin');
  assert.strictEqual(c('integer[]'), 'array');
  assert.strictEqual(c('tinyint(1)', 'mysql'), 'bool');
  assert.strictEqual(c('int unsigned', 'mysql'), 'int');
  assert.strictEqual(c('longtext', 'mysql'), 'text');
  assert.strictEqual(c('VARCHAR(100) FOR BIT DATA', 'db2'), 'bin');
  assert.strictEqual(c('', 'sqlite'), 'any');
  assert.strictEqual(c('BIGINT', 'sqlite'), 'int');
  assert.deepStrictEqual(category({ type: 'numeric(12,2)' }, 'pg'), { cat: 'dec', p: 12, s: 2 });
});

test('types map to each target', () => {
  assert.strictEqual(targetType({ cat: 'json' }, 'mysql'), 'json');
  assert.strictEqual(targetType({ cat: 'bool' }, 'db2'), 'BOOLEAN');
  assert.strictEqual(targetType({ cat: 'varchar', len: 60 }, 'db2'), 'VARCHAR(240)');
  assert.strictEqual(targetType({ cat: 'text' }, 'mysql', { pk: true }), 'varchar(255)');
  assert.strictEqual(targetType({ cat: 'dec', p: 40, s: 2 }, 'db2'), 'DECIMAL(31,2)');
  assert.strictEqual(targetType({ cat: 'tstz' }, 'pg'), 'timestamptz');
});

test('CREATE TABLE keeps keys, identity and NOT NULL', () => {
  const cols = [
    { name: 'id', to: 'id', type: 'integer', pk: true, nullable: false, identity: true, c: { cat: 'int', size: 4 } },
    { name: 'name', to: 'name', type: 'character varying(60)', nullable: false, c: { cat: 'varchar', len: 60 } },
  ];
  assert.strictEqual(createTableSql({ src: 'pg', dst: 'mysql', schema: 'shop', table: 't', cols }),
    'CREATE TABLE `shop`.`t` (\n  `id` int AUTO_INCREMENT NOT NULL,\n  `name` varchar(60) NOT NULL,\n  PRIMARY KEY (`id`)\n)');
  assert.strictEqual(createTableSql({ src: 'pg', dst: 'sqlite', schema: 'main', table: 't', cols }),
    'CREATE TABLE "t" (\n  "id" INTEGER PRIMARY KEY,\n  "name" VARCHAR(60) NOT NULL\n)');
  assert.match(createTableSql({ src: 'mysql', dst: 'pg', schema: 's', table: 't', cols }), /"id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL/);
});

test('values are converted between engines', () => {
  assert.strictEqual(convert('t', { cat: 'bool' }, 'pg', 'mysql'), 1);
  assert.strictEqual(convert(0, { cat: 'bool' }, 'mysql', 'pg'), false);
  assert.deepStrictEqual(convert('\\xdeadbeef', { cat: 'bin' }, 'pg', 'sqlite'), Buffer.from('deadbeef', 'hex'));
  assert.strictEqual(convert('2026-01-02 10:20:30.123456+07', { cat: 'tstz' }, 'pg', 'mysql'), '2026-01-02 03:20:30.123456');
  assert.strictEqual(convert('2026-01-02-10.20.30.000001', { cat: 'ts' }, 'db2', 'pg'), '2026-01-02 10:20:30.000001');
  assert.strictEqual(convert(true, { cat: 'text' }, 'pg', 'sqlite'), 1);
  assert.strictEqual(convert('same', { cat: 'text' }, 'pg', 'pg'), 'same');
});

test('Db2 names change case only when asked and only for plain names', () => {
  assert.strictEqual(nameFor('orders', 'pg', 'db2', true), 'ORDERS');
  assert.strictEqual(nameFor('MixedCase', 'pg', 'db2', true), 'MixedCase');
  assert.strictEqual(nameFor('ORDERS', 'db2', 'mysql', true), 'orders');
  assert.strictEqual(nameFor('orders', 'pg', 'db2', false), 'orders');
});
